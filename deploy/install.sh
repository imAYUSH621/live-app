#!/usr/bin/env bash
# One-command installer for a fresh Ubuntu 22.04 / 24.04 VPS (Oracle Free, Hetzner, Contabo, DigitalOcean, Hostinger…)
#   sudo bash deploy/install.sh
# Re-running is safe: existing secrets in .env are kept.
set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf "\n\033[1;33m▶ %s\033[0m\n" "$*"; }
need_root() { [ "$(id -u)" -eq 0 ] || { echo "Run as root: sudo bash deploy/install.sh"; exit 1; }; }
rand() { tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-32}"; }
need_root

# ---------- 1. questions ----------
if [ -f .env ]; then
  say "Found existing .env — keeping your secrets"
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
fi
ask() { local var="$1" prompt="$2" def="${3:-}"; local cur="${!var:-$def}"; read -r -p "$prompt [${cur}]: " v; printf -v "$var" '%s' "${v:-$cur}"; }
ask BASE_DOMAIN "Your domain (e.g. myliveapp.com)" "${BASE_DOMAIN:-}"
[ -n "$BASE_DOMAIN" ] || { echo "Domain is required"; exit 1; }
ask APP_NAME "App name" "${APP_NAME:-LiveApp}"
ask ACME_EMAIL "Email for SSL certificates" "${ACME_EMAIL:-admin@$BASE_DOMAIN}"
ask ADMIN_EMAIL "Super-admin login email" "${ADMIN_EMAIL:-admin@$BASE_DOMAIN}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-$(rand 14)}"

APP_DOMAIN="app.$BASE_DOMAIN"; ADMIN_DOMAIN="admin.$BASE_DOMAIN"; LIVE_DOMAIN="live.$BASE_DOMAIN"
PUBLIC_IP="$(curl -4 -fsS https://api.ipify.org || curl -4 -fsS https://ifconfig.me || hostname -I | awk '{print $1}')"

# ---------- 2. secrets ----------
JWT_SECRET="${JWT_SECRET:-$(rand 48)}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-$(rand 24)}"
LIVEKIT_API_KEY="${LIVEKIT_API_KEY:-API$(rand 12)}"
LIVEKIT_API_SECRET="${LIVEKIT_API_SECRET:-$(rand 40)}"
TURN_SECRET="${TURN_SECRET:-$(rand 32)}"

cat > .env <<EOF
# ---- generated by deploy/install.sh — keep this file secret ----
APP_NAME=$APP_NAME
BASE_DOMAIN=$BASE_DOMAIN
APP_DOMAIN=$APP_DOMAIN
ADMIN_DOMAIN=$ADMIN_DOMAIN
LIVE_DOMAIN=$LIVE_DOMAIN
ACME_EMAIL=$ACME_EMAIL
PUBLIC_API_URL=https://$APP_DOMAIN
PUBLIC_APP_URL=https://$APP_DOMAIN
CORS_ORIGINS=https://$APP_DOMAIN,https://$ADMIN_DOMAIN
JWT_SECRET=$JWT_SECRET
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
ADMIN_EMAIL=$ADMIN_EMAIL
ADMIN_PASSWORD=$ADMIN_PASSWORD
LIVEKIT_URL=wss://$LIVE_DOMAIN
LIVEKIT_API_KEY=$LIVEKIT_API_KEY
LIVEKIT_API_SECRET=$LIVEKIT_API_SECRET
TURN_URLS=turn:$PUBLIC_IP:3478?transport=udp,turn:$PUBLIC_IP:3478?transport=tcp
TURN_SECRET=$TURN_SECRET

# ---- optional: fill these later, then run: docker compose up -d ----
# Google login: create an OAuth "Web application" client at console.cloud.google.com
GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID:-}
# Phone OTP: console (free, shows code in logs — testing only) or 2factor (2factor.in)
OTP_PROVIDER=${OTP_PROVIDER:-console}
TWOFACTOR_API_KEY=${TWOFACTOR_API_KEY:-}
# Razorpay (UPI / cards) — dashboard.razorpay.com → API keys; webhook URL: https://$APP_DOMAIN/api/webhooks/razorpay
RAZORPAY_KEY_ID=${RAZORPAY_KEY_ID:-}
RAZORPAY_KEY_SECRET=${RAZORPAY_KEY_SECRET:-}
RAZORPAY_WEBHOOK_SECRET=${RAZORPAY_WEBHOOK_SECRET:-}
# Firebase push (service account JSON on ONE line)
FIREBASE_SERVICE_ACCOUNT_JSON=${FIREBASE_SERVICE_ACCOUNT_JSON:-}
# AI moderation of live frames (sightengine.com free tier)
SIGHTENGINE_USER=${SIGHTENGINE_USER:-}
SIGHTENGINE_SECRET=${SIGHTENGINE_SECRET:-}
# Chat translation (self-hosted LibreTranslate URL)
LIBRETRANSLATE_URL=${LIBRETRANSLATE_URL:-}
EOF
chmod 600 .env

sed -e "s/__LIVEKIT_API_KEY__/$LIVEKIT_API_KEY/" -e "s/__LIVEKIT_API_SECRET__/$LIVEKIT_API_SECRET/" deploy/livekit.yaml.template > deploy/livekit.yaml
sed -e "s/__TURN_SECRET__/$TURN_SECRET/" -e "s/__DOMAIN__/$BASE_DOMAIN/" -e "s/__PUBLIC_IP__/$PUBLIC_IP/" deploy/turnserver.conf.template > deploy/turnserver.conf

# ---------- 3. docker ----------
if ! command -v docker >/dev/null; then
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker >/dev/null 2>&1 || true

# ---------- 4. swap (small VPS) ----------
if [ "$(free -m | awk '/Mem:/{print $2}')" -lt 3000 ] && ! swapon --show | grep -q swap; then
  say "Adding 2GB swap (helps the build on small servers)"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile && echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# ---------- 5. firewall ----------
say "Opening firewall ports"
if command -v ufw >/dev/null; then
  ufw allow 22/tcp; ufw allow 80/tcp; ufw allow 443/tcp
  ufw allow 7881/tcp; ufw allow 50000:50200/udp
  ufw allow 3478/tcp; ufw allow 3478/udp; ufw allow 49160:49250/udp
  ufw --force enable || true
fi
# Oracle Cloud images ship iptables rules that block everything except SSH
if iptables -L INPUT -n 2>/dev/null | grep -q "REJECT"; then
  for rule in "-p tcp --dport 80" "-p tcp --dport 443" "-p tcp --dport 7881" "-p udp --dport 50000:50200" "-p tcp --dport 3478" "-p udp --dport 3478" "-p udp --dport 49160:49250"; do
    # shellcheck disable=SC2086
    iptables -C INPUT $rule -j ACCEPT 2>/dev/null || iptables -I INPUT 5 $rule -j ACCEPT
  done
  command -v netfilter-persistent >/dev/null && netfilter-persistent save || true
fi

# ---------- 6. start ----------
say "Building and starting (first build takes 5–10 minutes)"
docker compose up -d --build

# ---------- 7. daily database backup ----------
cat > /etc/cron.daily/liveapp-backup <<EOF
#!/bin/sh
mkdir -p /var/backups/liveapp
cd $(pwd) && docker compose exec -T postgres pg_dump -U liveapp liveapp | gzip > /var/backups/liveapp/db-\$(date +%F).sql.gz
find /var/backups/liveapp -name 'db-*.sql.gz' -mtime +14 -delete
EOF
chmod +x /etc/cron.daily/liveapp-backup

cat <<EOF

=====================================================================
 ✅  $APP_NAME is starting.

 1) Point these DNS "A" records to $PUBLIC_IP (Cloudflare: DNS only / grey cloud):
      $APP_DOMAIN     $ADMIN_DOMAIN     $LIVE_DOMAIN
    SSL certificates are issued automatically once DNS points here.

 2) Open:
      User app     https://$APP_DOMAIN
      Admin panel  https://$ADMIN_DOMAIN
      Admin login  $ADMIN_EMAIL  /  $ADMIN_PASSWORD
    (Change the password and turn on 2FA from "My account".)

 3) Oracle / AWS / GCP users: also open these ports in the cloud firewall
    (Oracle: VCN → Security List → Ingress rules):
      TCP 80, 443, 7881, 3478    UDP 3478, 50000-50200, 49160-49250

 Logs:     docker compose logs -f api
 Update:   git pull && docker compose up -d --build
 Backups:  /var/backups/liveapp (daily, 14 days kept)
=====================================================================
EOF
